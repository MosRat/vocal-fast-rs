"""Serial, paired end-to-end CPU quantization benchmarks against Applio fixtures.

No operator-sum estimates: complete native pipelines execute the same inputs and
latent/NSF noise. The Python reference and calibration fixtures are generated by
experiment-cpu-w8a8-combinations.py. CPU affinity and threads are held constant.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import shutil
import numpy as np
from scipy.io import wavfile

ROOT = Path(__file__).resolve().parents[1]


def metric(a, b):
    a, b = np.asarray(a,dtype=np.float64).ravel(),np.asarray(b,dtype=np.float64).ravel()
    if a.shape != b.shape or not a.size or not np.isfinite(a).all() or not np.isfinite(b).all():
        raise ValueError("invalid comparison arrays")
    d = b-a
    return dict(cosine=float(np.dot(a,b)/max(np.linalg.norm(a)*np.linalg.norm(b),1e-30)),
                rmse=float(np.sqrt(np.mean(d*d))),max_abs=float(np.abs(d).max()),
                reference_rms=float(np.sqrt(np.mean(a*a))),actual_rms=float(np.sqrt(np.mean(b*b))))


def summarize(rows, rate):
    # Keep every window in the aggregate, and identify low-volume windows
    # separately. Never hide their errors by dropping them from the report.
    speech = [r for r in rows if r["applio"]["reference_rms"] >= .01]
    return dict(cosine_min=min(r["applio"]["cosine"] for r in rows),
                rmse_mean=float(np.mean([r["applio"]["rmse"] for r in rows])),
                max_abs=max(r["applio"]["max_abs"] for r in rows),
                speech_cosine_min=min((r["applio"]["cosine"] for r in speech),default=None),
                speech_windows=len(speech),low_volume_windows=len(rows)-len(speech),
                sample_rate=rate,windows=rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--directory",type=Path,default=ROOT/"target/cpu-w8a8/broad")
    ap.add_argument("--binary",type=Path,default=ROOT/"target/debug/examples/quantization_benchmark.exe")
    ap.add_argument("--iterations",type=int,default=32)
    ap.add_argument("--recipes",nargs="+")
    ap.add_argument("--resume",action="store_true",help="reuse completed pairs and calibration for unchanged artifacts")
    ap.add_argument("--inputs-from",type=Path,help="copy accuracy/inputs/recipes metadata from an existing experiment")
    ap.add_argument("--deconv-bn",choices=["fold","preserve"],default="fold")
    args = ap.parse_args()
    if args.iterations < 8: ap.error("at least 8 iterations required")
    if args.inputs_from:
        if args.inputs_from.resolve() == args.directory.resolve(): ap.error("inputs-from must differ from directory")
        args.directory.mkdir(parents=True,exist_ok=True)
        for name in ["accuracy.json","inputs.json","recipes.json"]:
            shutil.copyfile(args.inputs_from/name,args.directory/name)
    spec = importlib.util.spec_from_file_location("operators",ROOT/"scripts/benchmark-cpu-operators.py")
    ops = importlib.util.module_from_spec(spec); spec.loader.exec_module(ops)
    affinity = ops.performance_cpu_affinity()
    plans = json.loads((args.directory/"recipes.json").read_text())
    accuracy = json.loads((args.directory/"accuracy.json").read_text())
    fixture_meta = json.loads((args.directory/"inputs.json").read_text())
    source_paths = [ROOT/"target/default-canonical-with-index.vfr",ROOT/"models/shared/hubert_base/hubert_features.vfr",ROOT/"models/shared/rmvpe/rmvpe.vfr"]
    def digest(p):
        with p.open("rb") as file: return hashlib.file_digest(file,"sha256").hexdigest()
    hashes = {str(p):digest(p) for p in source_paths}
    contract = {"binary":digest(args.binary),"inputs":digest(args.directory/"inputs.json"),
                "recipes":digest(args.directory/"recipes.json"),"iterations":args.iterations,"sources":hashes,
                "deconv_batchnorm":args.deconv_bn}
    out = args.directory/"native"; out.mkdir(exist_ok=True)
    selected = args.recipes or list(plans)
    if any(n not in plans for n in selected): ap.error("unknown recipe")
    # Collect the union once from FP32 graphs, then merge channel maxima across
    # both fixed shapes. No held-out inputs contribute to activation scales.
    all_rules = {r["prefix"]:r for plan in plans.values() for r in plan["rules"]}
    union = out/"calibration-recipe.json"
    union.write_text(json.dumps(dict(rules=list(all_rules.values()),calibration={},fold_deconvolution_batchnorm=args.deconv_bn=="fold")))
    calibration = out/"calibration.json"
    def run(samples, recipe, directory, iterations, calibration_file=calibration):
        command = [str(args.binary.resolve()),*[str(p) for p in source_paths],str((args.directory/"inputs.json").resolve()),
                   str(recipe),str(calibration_file.resolve()),str(directory.resolve()),str(samples),str(iterations)]
        proc = subprocess.run(command,capture_output=True,text=True,env=os.environ)
        if proc.returncode: raise RuntimeError(f"{command}\n{proc.stderr or proc.stdout}")
        return json.loads(proc.stdout)
    saved = json.loads((args.directory/"native-results.json").read_text()) if args.resume and (args.directory/"native-results.json").is_file() else None
    if saved and saved.get("contract") != contract:
        raise ValueError("resume requires identical binary, sources, recipes, inputs and iterations")
    if not saved:
        merged = {}
        for samples in [11200,44960]:
            part = out/f"calibration-{samples}.json"
            info = run(samples,union.resolve(),out/f"calibrate-{samples}",0,part)
            for name, values in json.loads(part.read_text()).items():
                merged[name] = np.maximum(merged.get(name,np.zeros(len(values))),values).tolist()
            print(json.dumps(dict(calibration=info)),flush=True)
        calibration.write_text(json.dumps(merged))
    report = dict(reference=accuracy["reference"],sources_sha256=hashes,affinity=affinity,
                  calibration_windows=[w for w in fixture_meta["windows"] if w["split"]=="calibration"],
                  note="paired alternating FP32/INT8 in the same process, two pipelines resident, 8 warmup pairs, complete process_exact pipeline, 6 threads, index=0, FP32 output, static W8A8; weights [-127,127], activation [-128,127], zero point=0; identical noise; Q/layout and Smooth included; no per-node timing",
                  results=[])
    report["contract"] = contract
    report["deconv_batchnorm"] = args.deconv_bn
    report["eligible"] = accuracy.get("eligible")
    if saved: report = saved
    for samples in [11200,44960]:
        for k,label in enumerate(selected):
            if any(r["name"]==label and r["samples"]==samples for r in report["results"]): continue
            recipe = out/f"recipe-{label}.json"
            recipe.write_text(json.dumps(dict(plans[label],fold_deconvolution_batchnorm=args.deconv_bn=="fold")))
            quant_dir = out/f"{samples}-{label}-int8"
            q = run(samples,recipe.resolve(),quant_dir,args.iterations)
            b = q["baseline"]
            expected = next(r["coverage"] for r in accuracy["recipes"] if r["name"]==label)
            expected_layers = sum(c["layers"] for c in expected.values())
            expected_weights = sum(c["weight_elements"] for c in expected.values())
            if len(q["quantized"]) != expected_layers or sum(n["weight_elements"] for n in q["quantized"]) != expected_weights:
                raise RuntimeError(f"native recipe coverage differs from Python: {label}, {len(q['quantized'])} vs {expected_layers}")
            if any("vnni" not in n["implementation"] and "amx" not in n["implementation"] for n in q["quantized"]):
                raise RuntimeError("non-integer native implementation")
            comparisons = []
            for qo,bo in zip(q["outputs"],b["outputs"]):
                actual = np.fromfile(qo["audio"],dtype="<f4")
                baseline = np.fromfile(bo["audio"],dtype="<f4")
                fixture = Path(qo["reference_directory"])
                reference = np.fromfile(fixture/"reference.f32",dtype="<f4")
                stem = f"{qo['split']}-{qo['offset']}"
                pitch = np.fromfile(quant_dir/(stem+"-pitch.i32"),dtype="<i4")
                pitch_ref = np.fromfile(fixture/"pitch.i32",dtype="<i4")
                f0 = np.fromfile(quant_dir/(stem+"-pitchf.f32"),dtype="<f4")
                f0_ref = np.fromfile(fixture/"pitchf.f32",dtype="<f4")
                comparisons.append(dict(split=qo["split"],offset=qo["offset"],applio=metric(reference,actual),
                    native_fp32=metric(baseline,actual),fp32_applio=metric(reference,baseline),
                    coarse_mismatch=int(np.count_nonzero(pitch!=pitch_ref)),
                    voicing_mismatch=int(np.count_nonzero((f0>0)!=(f0_ref>0))),f0=metric(f0_ref,f0)))
                wavfile.write(str(quant_dir/(stem+".wav")),fixture_meta["sample_rate"],actual)
            speedup = b["mean_ms"]["total"]/q["mean_ms"]["total"]
            latency = dict(fp32=b["mean_ms"],int8=q["mean_ms"],speedup=speedup,
                           reduction_percent=100*(1-1/speedup),
                           fp32_p95_ms=float(np.percentile(np.asarray(b["rows_ms"])[:,-1],95)),
                           int8_p95_ms=float(np.percentile(np.asarray(q["rows_ms"])[:,-1],95)))
            row = dict(name=label,samples=samples,coverage=expected,latency=latency,audio=summarize(comparisons,fixture_meta["sample_rate"]),
                       quantized=q["quantized"],fp32_memory=b["memory"],int8_memory=q["memory"],
                       rows_ms=dict(fp32=b["rows_ms"],int8=q["rows_ms"]))
            row["build_ms"] = dict(fp32=b["build_ms"],int8=q["build_ms"])
            report["results"].append(row)
            (args.directory/"native-results.json").write_text(json.dumps(report,indent=2)+"\n")
            print(json.dumps(dict(name=label,samples=samples,fp32_ms=latency["fp32"]["total"],int8_ms=latency["int8"]["total"],
                                 speedup=speedup,cosine_min=row["audio"]["cosine_min"],speech_cosine_min=row["audio"]["speech_cosine_min"],
                                 rmse=row["audio"]["rmse_mean"])),flush=True)


if __name__ == "__main__": main()
